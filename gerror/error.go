package gerror

import (
	"fmt"
	"path/filepath"
	"runtime"
	"strings"
)

type stack []uintptr

const maxStackDepth = 32

func callers(skip ...int) stack {
	var pcs [maxStackDepth]uintptr
	n := 3
	if len(skip) > 0 {
		n += skip[0]
	}
	cnt := runtime.Callers(n, pcs[:])
	return pcs[:cnt]
}

type Error struct {
	Cause  error
	Stack  stack
	Code   int
	Msg    string //对外可输出
	Detail string //对内显示
}

const stackFilterKey = "/errors/gerror/gerror"

type Frame struct {
	File string
	Line int
	Func string
}

func (err Error) StackFrame(row int) Frame {
	if row < 0 {
		return Frame{File: "", Line: 0, Func: ""}
	}
	frames := runtime.CallersFrames(err.Stack)
	i := 0
	for {
		f, more := frames.Next()
		file := filepath.ToSlash(f.File)
		fn := f.Function
		if f.Line != 0 && fn != "" && !shouldFilterFrame(file, fn) {
			if i == row {
				return Frame{Line: f.Line, File: file, Func: fn}
			}
			i++
		}
		if !more {
			break
		}
	}
	return Frame{File: "", Line: 0, Func: ""}
}

